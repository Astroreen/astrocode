// T4 spike orchestrator: reachability of aliased tool names (Task_Create /
// TodoWrite / Agent) through the meridian path on the server.
//
// Plan: .sisyphus/plans/2026-10-10-astrocode-telemetry-cache-reliability.md (B0, T4).
//
// What it does (evidence-gathering spike, NOT production code):
//   1. Generates a minimal probe plugin (registers tools Task_Create, TodoWrite,
//      Agent; each execute appends a marker JSONL line; tool.execute.before
//      records every invoked tool name as seen by opencode) plus a minimal QA
//      opencode.jsonc replicating the server's real anthropic->meridian provider.
//   2. Stages the QA tree to astroreen@server:/tmp/opencode-qa-b0 (isolated
//      XDG_CONFIG_HOME; the server's real config is never modified).
//   3. Runs exactly 3 headless `opencode run` sessions (one per alias name),
//      each with a short Russian prompt asking the model to call that tool.
//   4. Fetches marker files + run transcripts back and writes per-alias
//      marker-<alias>.log files plus summary.json under the T4 evidence dir.
//
// Outcome semantics:
//   - marker fired  -> Outcome A (alias reached the opencode tool registry).
//   - no marker but model "succeeded" -> Outcome B (call swallowed by the
//     native Claude Code SDK layer inside meridian or errored pre-registry).
//   - meridian/ssh unreachable -> honest inconclusive (meridian-down.log).
//
// Usage: bun spike/probe-alias-reach.ts
// Quota note: each run consumes real Claude Max quota via meridian — the
// script performs exactly 3 model calls, nothing more.

