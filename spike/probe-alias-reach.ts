async function ssh(command: string, timeoutMs: number): Promise<string> {
  const result = await runLocal(
    "ssh",
    ["-o", "BatchMode=yes", "-o", "ConnectTimeout=15", HOST, command],
    { timeout: timeoutMs, encoding: "utf8" },
  )
  return result.stdout
}

async function scp(localPath: string, remotePath: string): Promise<void> {
  await runLocal(
    "scp",
    ["-o", "BatchMode=yes", "-o", "ConnectTimeout=15", "-r", localPath, HOST + ":" + remotePath],
    { timeout: 120_000, encoding: "utf8" },
  )
}

async function scpBack(remotePath: string, localPath: string): Promise<void> {
  await runLocal(
    "scp",
    ["-o", "BatchMode=yes", "-o", "ConnectTimeout=15", "-r", HOST + ":" + remotePath, localPath],
    { timeout: 120_000, encoding: "utf8" },
  )
}

async function preflight(): Promise<void> {
  // meridian service state
  let serviceState = "unknown"
  try {
    serviceState = (await ssh("systemctl --user is-active meridian", 30_000)).trim()
  } catch (error) {
    serviceState = "ssh-failed: " + String(error)
  }
  await writeFile(join(EVIDENCE, "preflight-service.txt"), serviceState + "\n")

  if (serviceState !== "active") {
    const detail = serviceState + "\n"
    await writeFile(join(EVIDENCE, "meridian-down.log"), detail)
    throw new Error("probe inconclusive: meridian unreachable (service state: " + serviceState + ")")
  }

  // meridian HTTP reachability (any HTTP status proves the port answers)
  let httpProbe = "curl-failed"
  try {
    httpProbe = (
      await ssh(
        'curl -s -o /dev/null -m 10 -w "%{http_code}" http://127.0.0.1:3456/ || true',
        30_000,
      )
    ).trim()
  } catch (error) {
    httpProbe = "curl-error: " + String(error)
  }
  await writeFile(join(EVIDENCE, "preflight-http.txt"), httpProbe + "\n")

  if (httpProbe === "curl-failed" || httpProbe.startsWith("curl-error") || httpProbe === "000") {
    const detail = "service=active http=" + httpProbe + "\n"
    await writeFile(join(EVIDENCE, "meridian-down.log"), detail)
    throw new Error("probe inconclusive: meridian unreachable (http probe: " + httpProbe + ")")
  }

  // model availability (exact id must exist on the server)
  const modelCheck = (
    await ssh(
      "opencode models 2>/dev/null | grep -c '^" + MODEL + "$' || true",
      60_000,
    )
  ).trim()
  await writeFile(join(EVIDENCE, "preflight-model.txt"), MODEL + " count=" + modelCheck + "\n")
  if (modelCheck === "0") {
    throw new Error("model " + MODEL + " not present on server; aborting before any quota spend")
  }
}

async function stageQaTree(): Promise<void> {
  const pluginDir = join(STAGE, "qa", "opencode", "plugin")
  await mkdir(pluginDir, { recursive: true })
  await mkdir(join(STAGE, "qa", "project"), { recursive: true })
  await writeFile(join(pluginDir, "probe-alias.ts"), PROBE_PLUGIN_SOURCE)
  await writeFile(join(STAGE, "qa", "opencode", "opencode.jsonc"), QA_CONFIG_SOURCE)

  // Fresh isolated QA tree on the server; node_modules symlink resolves
  // @opencode-ai/plugin for the probe plugin (read-only use of the real install).
  await ssh(
    "rm -rf " + QA_ROOT + " && mkdir -p " + QA_ROOT + "/opencode/plugin " + QA_ROOT + "/project " + QA_ROOT + "/markers",
    60_000,
  )
  await ssh(
    "ln -s /home/astroreen/.config/opencode/node_modules " + QA_ROOT + "/node_modules",
    30_000,
  )
  await scp(join(STAGE, "qa", "opencode", "opencode.jsonc"), QA_ROOT + "/opencode/opencode.jsonc")
  await scp(join(pluginDir, "probe-alias.ts"), QA_ROOT + "/opencode/plugin/probe-alias.ts")

  // Sanity: the staged plugin must be readable and free of sanitizer artifacts.
  const roundTrip = await ssh("cat " + QA_ROOT + "/opencode/plugin/probe-alias.ts | md5sum", 30_000)
  const local = await readFile(join(pluginDir, "probe-alias.ts"), "utf8")
  if (local.includes("__POTENTIAL_")) {
    throw new Error("sanitizer artifact detected in staged plugin source; aborting")
  }
  await writeFile(join(EVIDENCE, "staging-md5.txt"), "local-md5-vs-remote: " + roundTrip.trim() + " local-bytes=" + String(local.length) + "\n")
}

interface RunResult {
  alias: string
  ok: boolean
  stdout: string
  stderr: string
  errorText: string
}

async function runAlias(probe: AliasProbe): Promise<RunResult> {
  // Fresh markers per alias so evidence is unambiguous.
  await ssh("rm -rf " + QA_ROOT + "/markers && mkdir -p " + QA_ROOT + "/markers", 30_000)

  // `timeout 240` on the remote side guarantees the headless opencode process
  // dies even if ssh is killed first (a killed ssh leaves the remote process
  // running, which caused retry storms during the first T4 execution).
  const remoteCommand =
    "cd " + QA_ROOT + "/project" +
    " && XDG_CONFIG_HOME=" + QA_ROOT +
    " timeout 240 opencode run --model " + MODEL +
    " '" + probe.prompt.replace(/'/g, "'\\''") + "'" +
    " 2>/tmp/opencode-qa-b0/run-stderr.log"
  // stdout of opencode run is the transcript; stderr goes to a remote file we
  // fetch separately (opencode serve-style processes dislike closed stderr).
  let stdout = ""
  let stderr = ""
  let errorText = ""
  let ok = true
  try {
    const result = await runLocal(
      "ssh",
      ["-o", "BatchMode=yes", "-o", "ConnectTimeout=15", HOST, remoteCommand],
      { timeout: 300_000, encoding: "utf8", maxBuffer: 16 * 1024 * 1024 },
    )
    stdout = result.stdout
    stderr = result.stderr
  } catch (error) {
    ok = false
    const err = error as { stdout?: string; stderr?: string; message?: string; killed?: boolean }
    stdout = err.stdout ?? ""
    stderr = err.stderr ?? ""
    errorText = (err.killed ? "TIMEOUT after 300s: " : "") + String(err.message ?? error)
  }

  // Fetch markers + remote stderr.
  const markerDir = join(STAGE, "markers-" + probe.name)
  await rm(markerDir, { recursive: true, force: true })
  await mkdir(markerDir, { recursive: true })
  try {
    await scpBack(QA_ROOT + "/markers", markerDir)
  } catch (error) {
    await writeFile(join(markerDir, "scp-failed.txt"), String(error) + "\n")
  }
  try {
    await scpBack(QA_ROOT + "/run-stderr.log", join(markerDir, "run-stderr.log"))
  } catch (error) {
    await writeFile(join(markerDir, "stderr-scp-failed.txt"), String(error) + "\n")
  }

  // Dump the Claude Code SDK session transcripts meridian wrote for this QA
  // project dir. These show whether the model produced any tool_use at all
  // (and with which tool name) even when the opencode-level run fails.
  const pySource = [
    "import json,glob,os",
    "out=[]",
    "for p in sorted(glob.glob('/home/astroreen/.claude/projects/-tmp-opencode-qa-b0-project/*.jsonl')):",
    "    r={'file':os.path.basename(p),'tool_use':[],'errors':[]}",
    "    for line in open(p):",
    "        try: o=json.loads(line)",
    "        except Exception: continue",
    "        m=(o.get('message') or {});c=m.get('content')",
    "        if isinstance(c,list):",
    "            for b in c:",
    "                if isinstance(b,dict) and b.get('type')=='tool_use':",
    "                    r['tool_use'].append({'name':b.get('name'),'input':b.get('input')})",
    "        if o.get('isApiErrorMessage') or (isinstance(c,str) and 'extra usage' in c):",
    "            r['errors'].append(str(c)[:200])",
    "    out.append(r)",
    "print(json.dumps(out,ensure_ascii=False))",
  ].join("\n")
  const dumpRemote = "python3 -c " + JSON.stringify(pySource) + " > /tmp/opencode-qa-b0/sdk-transcripts.json"
  try {
    await ssh(dumpRemote, 60_000)
    await scpBack(QA_ROOT + "/sdk-transcripts.json", join(markerDir, "sdk-transcripts.json"))
  } catch (error) {
    await writeFile(join(markerDir, "sdk-dump-failed.txt"), String(error) + "\n")
  }

  return { alias: probe.name, ok, stdout, stderr, errorText }
}

function extractNames(jsonl: string, kind: string): Array<string> {
  const names: Array<string> = []
  for (const line of jsonl.split("\n")) {
    const trimmed = line.trim()
    if (trimmed.length === 0) continue
    try {
      const parsed = JSON.parse(trimmed) as { kind?: string; name?: string }
      if (parsed.kind === kind && typeof parsed.name === "string") {
        names.push(parsed.name)
      }
    } catch {
      names.push("<unparseable-line>")
    }
  }
  return names
}

async function main(): Promise<void> {
  await mkdir(EVIDENCE, { recursive: true })
  await mkdir(STAGE, { recursive: true })

  await preflight()
  await stageQaTree()

  const summary: Array<Record<string, unknown>> = []

  for (const probe of ALIASES) {
    const result = await runAlias(probe)

    let beforeJsonl = ""
    let executeJsonl = ""
    try {
      beforeJsonl = await readFile(join(STAGE, "markers-" + probe.name, "markers", "before.jsonl"), "utf8")
    } catch {
      beforeJsonl = ""
    }
    try {
      executeJsonl = await readFile(join(STAGE, "markers-" + probe.name, "markers", "execute.jsonl"), "utf8")
    } catch {
      executeJsonl = ""
    }

    const beforeNames = extractNames(beforeJsonl, "before")
    const executeNames = extractNames(executeJsonl, "execute")
    const markerFired = executeNames.includes(probe.name)

    // SDK-level view: did the model produce ANY tool_use inside the meridian
    // SDK session, regardless of the opencode-level outcome?
    let sdkToolUse: Array<{ name: string | null }> = []
    let sdkErrors: Array<string> = []
    try {
      const sdkRaw = await readFile(
        join(STAGE, "markers-" + probe.name, "markers", "sdk-transcripts.json"),
        "utf8",
      )
      const sdkSessions = JSON.parse(sdkRaw) as Array<{
        tool_use?: Array<{ name: string | null }>
        errors?: Array<string>
      }>
      for (const session of sdkSessions) {
        sdkToolUse = sdkToolUse.concat(session.tool_use ?? [])
        sdkErrors = sdkErrors.concat(session.errors ?? [])
      }
    } catch {
      // sdk-transcripts.json absent (dump failed) — recorded as such below.
    }

    // Per-alias evidence log: command, status, transcript, raw marker lines.
    const logLines: Array<string> = []
    logLines.push("== T4 probe run ==")
    logLines.push("alias: " + probe.name)
    logLines.push("model: " + MODEL)
    logLines.push("prompt: " + probe.prompt)
    logLines.push("run ok: " + String(result.ok))
    if (result.errorText.length > 0) logLines.push("run error: " + result.errorText)
    logLines.push("")
    logLines.push("-- stdout (model transcript) --")
    logLines.push(result.stdout.trimEnd())
    logLines.push("")
    logLines.push("-- stderr (local ssh) --")
    logLines.push(result.stderr.trimEnd())
    logLines.push("")
    logLines.push("-- tool.execute.before names (raw invoked-name lines follow) --")
    logLines.push(beforeJsonl.trimEnd())
    logLines.push("")
    logLines.push("-- execute marker lines (raw) --")
    logLines.push(executeJsonl.trimEnd())
    logLines.push("")
    logLines.push("-- verdict fields --")
    logLines.push("markerFired: " + String(markerFired))
    logLines.push("executeNames: " + JSON.stringify(executeNames))
    logLines.push("beforeNames: " + JSON.stringify(beforeNames))
    logLines.push("sdkToolUseNames: " + JSON.stringify(sdkToolUse.map((entry) => entry.name)))
    logLines.push("sdkErrorCount: " + String(sdkErrors.length))
    if (sdkErrors.length > 0) {
      logLines.push("sdkErrorSample: " + sdkErrors[0])
    }
    await writeFile(join(EVIDENCE, "marker-" + probe.name + ".log"), logLines.join("\n") + "\n")

    summary.push({
      alias: probe.name,
      markerFired,
      executeNames,
      beforeNames,
      sdkToolUseNames: sdkToolUse.map((entry) => entry.name),
      sdkErrorCount: sdkErrors.length,
      runOk: result.ok,
      runError: result.errorText,
      transcriptBytes: result.stdout.length,
    })
  }

  await writeFile(join(EVIDENCE, "summary.json"), JSON.stringify(summary, null, 2) + "\n")
  console.log(JSON.stringify(summary, null, 2))
}

main().catch(async (error) => {
  const message = error instanceof Error ? error.message : String(error)
  console.error("T4 probe failed: " + message)
  try {
    const existing = await readFile(join(EVIDENCE, "meridian-down.log"), "utf8").catch(() => "")
    if (message.includes("meridian unreachable") && existing.length === 0) {
      await writeFile(join(EVIDENCE, "meridian-down.log"), message + "\n")
    }
  } catch (writeError) {
    console.error("evidence write failed: " + String(writeError))
  }
  process.exit(1)
})